// Builds data/itemDescriptions.js: tooltip text for every item and add-on.
//
// Dev-only. Never runs for a player. Perk descriptions have always come from
// a script kept outside this repo; items and add-ons get their own script
// here instead of joining that one, because their source data
// (DBDBuilds' src/lib/itemData.ts) is a different shape and this repo
// already has to parse it for build-cards.mjs.
//
// The description text itself needs no translation: itemData.ts already
// writes it in the same markup ui/tooltip.js's parser was built for
// (**bold**, _italic_, {Status}), because it comes from the same wiki
// convention perk text does.
//
// Usage:  node tools/build-descriptions.mjs
//         DBDBUILDS=/path/to/DBDBuilds node tools/build-descriptions.mjs

import fs from 'node:fs';
import path from 'node:path';

const REPO = path.resolve(import.meta.dirname, '..');
const SRC = process.env.DBDBUILDS
  ?? 'C:/Users/ramzi/OneDrive/Documents/GitHub/DBDBuilds';

const itemDataPath = path.join(SRC, 'src/lib/itemData.ts');

if (!fs.existsSync(itemDataPath)) {
  console.error(`Cannot find DBDBuilds' itemData.ts at ${itemDataPath}\nSet DBDBUILDS=/path/to/DBDBuilds`);
  process.exit(1);
}

const itemData = fs.readFileSync(itemDataPath, 'utf8');

function section(name) {
  const i = itemData.indexOf('export const ' + name);
  if (i === -1) throw new Error(`missing export: ${name}`);
  const s = itemData.indexOf('= {', i) + 2;
  return itemData.slice(s, itemData.indexOf('\n};', s));
}

const ITEM_LINE = /^\s*(?:'([^']*)'|"([^"]*)"):\s*\{\s*type:\s*'[^']+',\s*color:\s*'[^']+',\s*desc:\s*'((?:[^'\\]|\\.)*)'/;
const ADDON_LINE = /^\s*(?:'([^']*)'|"([^"]*)"):\s*\{\s*color:\s*'[^']+',\s*desc:\s*'((?:[^'\\]|\\.)*)'/;

/** Undoes the single-quoted JS string escaping itemData.ts writes its desc
    fields in (\' and \\), so the raw wiki markup underneath comes through
    unescaped for PL.tooltip's own parser to read. */
function unescapeJsString(raw) {
  return raw.replace(/\\(.)/g, '$1');
}

function readDescriptions(sectionName, lineRegex) {
  const map = new Map();
  for (const line of section(sectionName).split('\n')) {
    const m = line.match(lineRegex);
    if (!m) continue;
    const name = m[1] ?? m[2];
    map.set(name, unescapeJsString(m[3]));
  }
  return map;
}

const itemDesc = readDescriptions('ITEM_INFO', ITEM_LINE);
const addonDesc = readDescriptions('SURVIVOR_ADDON_INFO', ADDON_LINE);

// ── Load this repo's own pool -- only cards actually in it get an entry ────

const baseline = JSON.parse(fs.readFileSync(path.join(REPO, 'tools/pool-baseline.json'), 'utf8'));

const wanted = baseline.names
  .map((line) => { const [name, , type] = line.split('|'); return { name, type }; })
  .filter((c) => c.type === 'Item' || c.type === 'Addon');

const found = {};
const missing = [];

for (const card of wanted) {
  const source = card.type === 'Item' ? itemDesc : addonDesc;
  const text = source.get(card.name);
  if (text) {
    found[card.name] = text;
  } else {
    missing.push(card.name);
  }
}

// ── Emit data/itemDescriptions.js ───────────────────────────────────────────

const body = Object.entries(found)
  .map(([name, text]) => `    ${JSON.stringify(name)}: ${JSON.stringify(text)}`)
  .join(',\n');

const out = `// GENERATED by tools/build-descriptions.mjs — do not edit by hand.
//
// Tooltip text for every item and add-on, keyed by card.name, in the same
// markup ui/tooltip.js's parser already handles for perks. Merged with
// perkDescriptions at lookup time (see PL.tooltip.hasDescription) rather
// than joining that file, since perk descriptions are generated by a
// separate script this repo does not own.

const itemDescriptions = {
${body}
};
`;

fs.writeFileSync(path.join(REPO, 'data/itemDescriptions.js'), out);

console.log(`descriptions   ${Object.keys(found).length} of ${wanted.length} items/add-ons`);
if (missing.length) {
  console.log(`no description found for: ${missing.join(', ')}`);
}
